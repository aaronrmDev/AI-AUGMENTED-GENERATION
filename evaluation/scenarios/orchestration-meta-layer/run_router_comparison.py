"""Router comparison: lexical cues vs. MiniLM nearest-prototype vs. qwen3.5, on
the held-out routing set. Not pytest-collected. Needs Ollama with qwen3.5.

Usage (from the repository root):
    PYTHONPATH=. python evaluation/scenarios/orchestration-meta-layer/run_router_comparison.py
"""
import asyncio
import io
import sys
import time
from pathlib import Path
from typing import Any

import ollama
import yaml

from evaluation.domain.routing_metrics import RoutingObservation, summarize
from evaluation.infrastructure.routing_report import render_router_comparison
from src.orchestration.domain.entities import Paradigm, RoutingDecision
from src.orchestration.domain.errors import ClassificationFailed
from src.orchestration.domain.paradigm_router import decide, fallback_decision
from src.orchestration.domain.ports import QueryClassifier
from src.orchestration.infrastructure.lexical_query_classifier import LexicalQueryClassifier
from src.orchestration.infrastructure.llm_query_classifier import LlmQueryClassifier
from src.orchestration.infrastructure.prototype_query_classifier import (
    PrototypeQueryClassifier,
)
from src.rag.infrastructure.ollama_chat_model import OllamaChatModel
from src.rag.infrastructure.sentence_transformers_embedder import SentenceTransformersEmbedder

_QUERIES = Path(__file__).parent / "routing_queries.yaml"
_REPORT = Path("evaluation/reports/orchestration-meta-layer-router.md")


def _ms(started: float) -> float:
    return (time.perf_counter() - started) * 1000


async def _classify(
    classifier: QueryClassifier, query: str, embedding: list[float]
) -> RoutingDecision:
    # The same mapping UnifiedAnswerQuestion applies: a classification failure
    # routes every tier in parallel. Counted separately via parse_failures.
    try:
        return decide(await classifier.score(query, embedding))
    except ClassificationFailed:
        return fallback_decision()


async def _observe(
    classifier: QueryClassifier,
    queries: list[dict[str, Any]],
    embeddings: dict[str, list[float]],
) -> list[RoutingObservation]:
    observations = []
    for entry in queries:
        query = str(entry["query"])
        expected = frozenset(Paradigm(str(value)) for value in entry["expected"])
        started = time.perf_counter()
        decision = await _classify(classifier, query, embeddings[query])
        observations.append(RoutingObservation(query, expected, decision, _ms(started)))
    return observations


async def _run() -> None:
    queries: list[dict[str, Any]] = yaml.safe_load(_QUERIES.read_text(encoding="utf-8"))[
        "queries"
    ]
    embedder = SentenceTransformersEmbedder()
    embedder.embed("warm up")
    embed_ms: list[float] = []
    embeddings: dict[str, list[float]] = {}
    for entry in queries:
        started = time.perf_counter()
        embeddings[entry["query"]] = embedder.embed(entry["query"])
        embed_ms.append(_ms(started))
    embed_ms.sort()

    llm = LlmQueryClassifier(OllamaChatModel(ollama.AsyncClient(), "qwen3.5"))
    classifiers: dict[str, QueryClassifier] = {
        "lexical": LexicalQueryClassifier(),
        "prototype (MiniLM, k=5)": PrototypeQueryClassifier(embedder),
        "llm (qwen3.5)": llm,
    }
    for classifier in classifiers.values():  # untimed warm-up: model load is not routing cost
        await _classify(classifier, "warm up", embeddings[queries[0]["query"]])
    llm.parse_failures = 0

    observations = {
        name: await _observe(classifier, queries, embeddings)
        for name, classifier in classifiers.items()
    }
    metrics = {name: summarize(observed) for name, observed in observations.items()}
    generated = sum(1 for entry in queries if entry["source"] != "concept-1-table")
    reviewed = sum(1 for entry in queries if entry.get("review_note"))
    notes = (
        f"{len(queries)} queries: {generated} generated by qwen3.5 after the classifiers were "
        f"committed, {reviewed} of their labels corrected by hand review, plus Concept 1's six "
        f"example queries verbatim. Latency is classify + decide only. Query embedding is paid "
        f"once per question by UnifiedAnswerQuestion whichever classifier runs, and is "
        f"measured separately here: p50 {embed_ms[len(embed_ms) // 2]:.2f}ms, max "
        f"{embed_ms[-1]:.2f}ms (MiniLM, CPU). A query with no signal, and any classification "
        f"failure, routes to every paradigm in parallel (fallback_decision). LLM classifier "
        f"parse failures: {llm.parse_failures} of {len(queries)}."
    )
    report = render_router_comparison(metrics, observations, notes)
    _REPORT.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    # The report can contain characters the Windows console's cp1252 can't
    # encode; the cascade runner crashed on exactly that after writing its reports.
    if isinstance(sys.stdout, io.TextIOWrapper):
        sys.stdout.reconfigure(encoding="utf-8")
    asyncio.run(_run())
